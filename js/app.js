    let pbCurrentBook = 'book1';
    let pbCurrentPage = 0;

    function pbRenderTabs() {
      const tabs = document.getElementById('pbTabs');
      tabs.innerHTML = Object.keys(processBooks).map(key => `
        <div class="process-book-tab ${key === pbCurrentBook ? 'active' : ''}" onclick="pbSwitchBook('${key}')">
          ${processBooks[key].label}
        </div>
      `).join('');
    }

    function pbSwitchBook(bookKey) {
      pbCurrentBook = bookKey;
      pbCurrentPage = 0;
      pbRenderTabs();
      pbRender();
    }

    function pbRender() {
      const book = processBooks[pbCurrentBook];
      const page = book.pages[pbCurrentPage];
      const content = document.getElementById('pbPageContent');
      const title = document.getElementById('pbTitle');
      const count = document.getElementById('pbCount');
      const dots = document.getElementById('pbDots');
      const prevBtn = document.getElementById('pbPrevBtn');
      const nextBtn = document.getElementById('pbNextBtn');

      title.textContent = book.label;

      content.innerHTML = `
        <span class="process-page-tag">${page.tag}</span>
        <h2 class="process-page-title">${page.title}</h2>
        <div class="process-page-body">${page.body}</div>
        ${page.note ? `<div class="process-page-note">${page.note}</div>` : ''}
      `;

      count.textContent = `Page ${pbCurrentPage + 1} of ${book.pages.length}`;
      prevBtn.disabled = pbCurrentPage === 0;
      nextBtn.disabled = pbCurrentPage === book.pages.length - 1;

      dots.innerHTML = book.pages.map((_, i) =>
        `<span class="process-page-dot ${i === pbCurrentPage ? 'active' : ''}" onclick="pbGoTo(${i})"></span>`
      ).join('');
    }

    function pbGoTo(index) {
      const book = processBooks[pbCurrentBook];
      if (index < 0 || index >= book.pages.length) return;
      pbCurrentPage = index;
      pbRender();
    }

    pbRenderTabs();
    pbRender(); 



    // Section Switcher with Navigation Highlight
    function showSection(sectionId) {
      const sections = document.querySelectorAll('.content-section');
      sections.forEach(section => section.classList.remove('active'));

      const targetSection = document.getElementById(sectionId);
      if (targetSection) {
        targetSection.classList.add('active');
        window.scrollTo({
          top: 0,
          behavior: 'smooth'
        });
      }

      // Close search overlay on section switch
      closeSearchOverlay();
    }

    // Open the expanding search overlay (covers the full header incl. nav)
    function openSearchOverlay() {
      const overlay = document.getElementById('searchOverlay');
      const toggleBtn = document.querySelector('.search-toggle-btn');
      overlay.classList.add('active');
      toggleBtn.setAttribute('aria-expanded', 'true');
      document.getElementById('siteSearchInput').focus();
    }

    // Close the search overlay and reset its state
    function closeSearchOverlay() {
      const overlay = document.getElementById('searchOverlay');
      const toggleBtn = document.querySelector('.search-toggle-btn');
      const panel = document.getElementById('searchResultsPanel');
      const input = document.getElementById('siteSearchInput');

      overlay.classList.remove('active');
      toggleBtn.setAttribute('aria-expanded', 'false');
      panel.classList.remove('active');
      panel.innerHTML = '';
      input.value = '';
    }

    // Interactive Site Content Search Engine
    function performSearch() {
      const input = document.getElementById('siteSearchInput');
      const query = input.value.trim().toLowerCase();
      const panel = document.getElementById('searchResultsPanel');

      if (query.length === 0) {
        panel.innerHTML = '';
        panel.classList.remove('active');
        return;
      }

      const sections = document.querySelectorAll('.content-section');
      let results = [];

      sections.forEach(section => {
        const sectionId = section.getAttribute('id');
        const sectionHeader = section.querySelector('h1')?.innerText || sectionId;

        // Search in section headings, paragraphs, and list items
        const textNodes = section.querySelectorAll('h1, h2, h3, p, li, td');

        textNodes.forEach(node => {
          const text = node.innerText;
          const matchIndex = text.toLowerCase().indexOf(query);

          if (matchIndex !== -1) {
            // Context snippet around the matched keyword
            const start = Math.max(0, matchIndex - 30);
            const end = Math.min(text.length, matchIndex + query.length + 50);
            let snippet = text.substring(start, end);

            if (start > 0) snippet = '...' + snippet;
            if (end < text.length) snippet = snippet + '...';

            // Highlight keyword matching
            const highlightedSnippet = snippet.replace(
              new RegExp(`(${escapeRegExp(query)})`, 'gi'),
              '<span class="search-highlight">$1</span>'
            );

            results.push({
              sectionId: sectionId,
              sectionHeader: sectionHeader,
              snippet: highlightedSnippet
            });
          }
        });
      });

      // Render search panel results
      if (results.length > 0) {
        let resultsHtml = '';
        // Limit display to top 15 results for performance
        results.slice(0, 15).forEach(res => {
          resultsHtml += `
            <div class="search-result-item" onclick="navigateToResult('${res.sectionId}')">
              <div class="search-result-title">${res.sectionHeader}</div>
              <div class="search-result-snippet">${res.snippet}</div>
            </div>
          `;
        });
        panel.innerHTML = resultsHtml;
        panel.classList.add('active');
      } else {
        panel.innerHTML = '<div class="no-results">No matching content found</div>';
        panel.classList.add('active');
      }
    }

    // Regex Escape Helper
    function escapeRegExp(string) {
      return string.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    }

    // Navigate to section from search result
    function navigateToResult(sectionId) {
      showSection(sectionId);
    }

    // Close the search overlay when clicking outside it (icon button and results panel excluded)
    document.addEventListener('click', function(e) {
      const overlay = document.getElementById('searchOverlay');
      const toggleBtn = document.querySelector('.search-toggle-btn');
      const panel = document.getElementById('searchResultsPanel');

      if (!overlay.classList.contains('active')) return;

      const clickedInsideOverlay = overlay.contains(e.target);
      const clickedToggleBtn = toggleBtn.contains(e.target);
      const clickedResultsPanel = panel.contains(e.target);

      if (!clickedInsideOverlay && !clickedToggleBtn && !clickedResultsPanel) {
        closeSearchOverlay();
      }
    });

    // Close the search overlay on Escape
    document.addEventListener('keydown', function(e) {
      if (e.key === 'Escape') {
        closeSearchOverlay();
      }
    });

    // Darken the header toward black as the user scrolls down the page
    function updateHeaderOnScroll() {
      const header = document.querySelector('.top-header');
      const overlay = document.getElementById('searchOverlay');
      const scrolled = window.scrollY > 10;

      header.classList.toggle('scrolled', scrolled);
      overlay.classList.toggle('scrolled', scrolled);
    }

    window.addEventListener('scroll', updateHeaderOnScroll);
    updateHeaderOnScroll();
